const initialLang = (typeof localStorage !== 'undefined' && localStorage.getItem('lang')) || 
  (typeof navigator !== 'undefined' && (navigator.language || '').toLowerCase().startsWith('uk') ? 'uk' : 'en');

export const currentLang = writable(initialLang);

export function setLanguage(lang) {
  currentLang.set(lang);
  if (typeof localStorage !== 'undefined') {
    localStorage.setItem('lang', lang);
  }
}

export const t = derived(currentLang, ($lang) => translations[$lang] || translations.en);

